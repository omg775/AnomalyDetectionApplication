-- Baseline: the schema as Hibernate created it before Flyway was introduced.
-- On an existing database Flyway records this version as the baseline and
-- does not execute it (spring.flyway.baseline-on-migrate=true). On an empty
-- database it creates the tables from scratch.

CREATE TABLE traffic_records (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    timestamp         TIMESTAMP(6) NOT NULL,
    source_ip         VARCHAR(255) NOT NULL,
    destination_ip    VARCHAR(255),
    destination_port  INTEGER      NOT NULL,
    protocol          VARCHAR(255) NOT NULL,
    bytes_transferred BIGINT       NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE anomaly_alerts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_ip    VARCHAR(255) NOT NULL,
    anomaly_type VARCHAR(255) NOT NULL,
    severity     VARCHAR(255) NOT NULL,
    timestamp    TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);
