package com.om.AnomalyDetectionApplication.migration;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.DynamicPropertyRegistry;
import org.springframework.test.context.DynamicPropertySource;
import org.testcontainers.junit.jupiter.Testcontainers;
import org.testcontainers.postgresql.PostgreSQLContainer;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Simulates the existing Supabase database: tables created by Hibernate before Flyway existed,
 * already holding data. Flyway must baseline it at V1 without touching the data, then apply the
 * later migrations. Skipped automatically when Docker is not available.
 */
@SpringBootTest
@Testcontainers(disabledWithoutDocker = true)
class ExistingDatabaseMigrationTest {

    private static PostgreSQLContainer container;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @DynamicPropertySource
    static void database(DynamicPropertyRegistry registry) {
        container = PostgresTestDatabase.start();
        PostgresTestDatabase.execute(container,
                "create table traffic_records (id bigint generated by default as identity, "
                        + "bytes_transferred bigint not null, destination_ip varchar(255), "
                        + "destination_port integer not null, protocol varchar(255) not null, "
                        + "source_ip varchar(255) not null, timestamp timestamp(6) not null, primary key (id))",
                "create table anomaly_alerts (id bigint generated by default as identity, "
                        + "anomaly_type varchar(255) not null, severity varchar(255) not null, "
                        + "source_ip varchar(255) not null, timestamp timestamp(6) not null, primary key (id))",
                "insert into traffic_records (bytes_transferred, destination_ip, destination_port, protocol, source_ip, timestamp) "
                        + "values (600000, '10.0.0.1', 80, 'TCP', '1.1.1.1', '2026-01-01 10:00:00'), "
                        + "(100, '10.0.0.1', 443, 'TCP', '1.1.1.2', '2026-01-01 11:00:00'), "
                        + "(300000, '10.0.0.1', 80, 'TCP', '1.1.1.3', '2026-01-02 09:00:00')",
                "insert into anomaly_alerts (anomaly_type, severity, source_ip, timestamp) "
                        + "values ('HIGH_TRAFFIC_VOLUME', 'HIGH', '1.1.1.1', '2026-01-01 10:00:00')");
        PostgresTestDatabase.register(registry, container);
    }

    @AfterAll
    static void stop() {
        if (container != null) {
            container.stop();
        }
    }

    @Test
    void existingSchemaIsBaselinedAtVersionOne() {
        String baselineType = jdbcTemplate.queryForObject(
                "SELECT type FROM flyway_schema_history WHERE version = '1'", String.class);
        Integer failed = jdbcTemplate.queryForObject(
                "SELECT COUNT(*) FROM flyway_schema_history WHERE success = false", Integer.class);

        assertThat(baselineType).isEqualTo("BASELINE");
        assertThat(failed).isZero();
    }

    @Test
    void existingDataIsPreserved() {
        assertThat(jdbcTemplate.queryForObject("SELECT COUNT(*) FROM traffic_records", Integer.class)).isEqualTo(3);
        assertThat(jdbcTemplate.queryForObject("SELECT COUNT(*) FROM anomaly_alerts", Integer.class)).isEqualTo(1);
    }
}
